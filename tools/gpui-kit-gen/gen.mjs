import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Docs, typeName } from './lib/rustdoc.mjs';
import { extractComponent, closureOf } from './lib/extract.mjs';
import { camel, kebab, mapType, pascal } from './lib/typemap.mjs';
import { extractState, eventVariants } from './lib/state.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const moduleDir = join(here, '../../modules/gpui-kit');
const docDir = process.env.KITGEN_DOCS ?? join(here, '.workspace/target/doc');
const components = JSON.parse(readFileSync(join(here, 'components.json'), 'utf8'));
const eventTable = JSON.parse(readFileSync(join(here, 'events.json'), 'utf8'));

const HEADER_TS = '// @generated by tools/gpui-kit-gen. Do not edit; edit components.json or the generator.\n';
const HEADER_RS = '// @generated by tools/gpui-kit-gen. Do not edit; edit components.json or the generator.\n';

const docs = new Docs(
  ['gpui_component', 'gpui_base', 'gpui_kit_assets'].map(n => join(docDir, `${n}.json`)),
);

function snake(name) {
  return name.replace(/([a-z0-9])([A-Z])/g, '$1_$2').replace(/-/g, '_').toLowerCase();
}

function enumVariantRust(literal) {
  return literal
    .split('-')
    .map(part => part[0].toUpperCase() + part.slice(1))
    .join('');
}

function buildModel(entry) {
  const component = extractComponent(docs, entry.path);
  const hit = docs.find(entry.path);
  const ctx = {
    docs,
    index: hit.index,
    publicPath: (index, id) => docs.publicPath(index, id),
  };
  const skip = entry.skip ?? {};
  const props = [];
  const events = [];
  const coverage = [];
  const used = new Set();

  const groups = new Map();
  for (const method of component.traitBuilders) {
    const match = method.name.match(/^with_(.+)$/);
    if (match) {
      const param = method.inputs[1];
      const mapped = param ? mapType(ctx, param[1]) : null;
      if (mapped?.kind === 'enum') groups.set(method.trait, { name: match[1], method });
    }
  }

  const methods = [
    ...component.builders.map(m => ({ ...m, origin: 'inherent' })),
    ...component.traitBuilders.map(m => ({ ...m, origin: m.trait })),
  ];
  for (const method of methods) {
    const label = `${component.name}::${method.name}`;
    const record = (outcome, reason, prop) => coverage.push({ item: label, outcome, reason, prop });
    if (skip[method.name]) {
      record('skipped', skip[method.name]);
      continue;
    }
    const params = method.inputs.slice(1);
    const group = groups.get(method.trait);
    if (group && group.method.name !== method.name && params.length === 0) {
      record('aliased', `covered by ${group.method.name}`, group.name);
      continue;
    }
    if (method.trait && /FocusableExt|DropdownMenu/.test(method.trait)) {
      record('skipped', `from ${method.trait.split('::').pop()}, not a component property`);
      continue;
    }
    let prop;
    if (params.length === 0) {
      prop = { name: camel(method.name), method: method.name, kind: 'flag' };
    } else if (params.length === 1) {
      const override = entry.props?.[method.name];
      const mapped = override ? { ...override } : mapType(ctx, params[0][1]);
      if (mapped.unsupported) {
        record('skipped', `unsupported: ${mapped.unsupported}`);
        continue;
      }
      const name = group && group.method.name === method.name ? camel(group.name) : camel(method.name);
      prop = { name, method: method.name, ...mapped };
    } else {
      record('skipped', `unsupported: takes ${params.length} arguments`);
      continue;
    }
    if (used.has(prop.name)) {
      record('skipped', `duplicate of the ${prop.name} prop`);
      continue;
    }
    used.add(prop.name);
    props.push(prop);
    record('generated', '', prop.name);
  }

  for (const extra of entry.extraProps ?? []) {
    const prop = { name: extra.name, method: null, extra: true, kind: extra.kind };
    if (extra.kind === 'enum') prop.info = { variants: extra.variants.map(v => v.replace(/(^|-)([a-z])/g, (_, __, c) => c.toUpperCase())), publicPath: null };
    used.add(prop.name);
    props.unshift(prop);
    coverage.push({ item: `${component.name} (prop ${extra.name})`, outcome: 'generated', reason: extra.reason ?? 'constructor argument', prop: extra.name });
  }

  for (const method of component.events) {
    const label = `${component.name}::${method.name}`;
    const eventName = entry.events?.[method.name];
    if (!eventName) {
      coverage.push({ item: label, outcome: 'skipped', reason: 'event not listed in components.json' });
      continue;
    }
    const closure = closureOf(method.inputs[method.inputs.length - 1][1]);
    const first = closure.inputs[0];
    const payloadName = first ? typeName(first).replace(/^&(mut )?/, '') : null;
    const payload = payloadName ? eventTable[payloadName.split('::').pop()] : null;
    if (!payload) {
      coverage.push({ item: label, outcome: 'skipped', reason: `unsupported: event payload ${payloadName ?? 'none'} has no entry in events.json` });
      continue;
    }
    events.push({ method: method.name, name: eventName, prop: `on${pascal(eventName)}`, nativeProp: `on${entry.tag}${pascal(eventName)}`, payload });
    coverage.push({ item: label, outcome: 'generated', reason: '', prop: `on${pascal(eventName)}` });
  }

  let state = null;
  if (entry.state) {
    const info = extractState(docs, entry.state.path);
    const stateCtx = { docs, index: info.index, publicPath: (index, id) => docs.publicPath(index, id) };
    const stateProps = [];
    const skipSetters = new Set(entry.state.skipSetters ?? []);
    const controlled = entry.state.controlled ?? null;
    for (const method of info.methods) {
      const label = `${info.resolved.item.name}::${method.name}`;
      if (!method.name.startsWith('set_') || method.selfKind !== 'mut') continue;
      if (controlled && method.name === controlled.setter) {
        coverage.push({ item: label, outcome: 'generated', reason: 'controlled value', prop: controlled.prop });
        continue;
      }
      const name = camel(method.name.slice(4));
      if (skipSetters.has(method.name)) {
        coverage.push({ item: label, outcome: 'skipped', reason: 'excluded in components.json' });
        continue;
      }
      if (method.data.length !== 1) {
        coverage.push({ item: label, outcome: 'skipped', reason: `unsupported: takes ${method.data.length} data arguments` });
        continue;
      }
      const mapped = mapType(stateCtx, method.data[0].type);
      if (mapped.unsupported || mapped.optional) {
        coverage.push({ item: label, outcome: 'skipped', reason: `unsupported: ${mapped.unsupported ?? 'an optional value has no unset sentinel'}` });
        continue;
      }
      if (used.has(name)) {
        coverage.push({ item: label, outcome: 'skipped', reason: `the ${name} prop comes from the element` });
        continue;
      }
      used.add(name);
      const prop = { name, method: method.name, ...mapped, source: 'state', needsWindow: method.needsWindow, needsCx: method.needsCx };
      stateProps.push(prop);
      coverage.push({ item: label, outcome: 'generated', reason: '', prop: name });
    }
    const commands = [];
    for (const [name, argSpec] of Object.entries(entry.state.commands ?? {})) {
      const method = info.methods.find(m => m.name === name);
      const label = `${info.resolved.item.name}::${name}`;
      if (!method) {
        coverage.push({ item: label, outcome: 'skipped', reason: 'command not found on the state' });
        continue;
      }
      commands.push({ name, method, args: Object.entries(argSpec).map(([argName, ts]) => ({ name: argName, ts })) });
      coverage.push({ item: label, outcome: 'generated', reason: 'command', prop: name });
    }
    const configured = entry.state.events ?? {};
    for (const enumPath of info.eventEnums) {
      for (const variant of eventVariants(docs, enumPath)) {
        const label = `${enumPath.split('::').pop()}::${variant.name}`;
        if (configured[variant.name]) coverage.push({ item: label, outcome: 'generated', reason: 'event', prop: `on${pascal(configured[variant.name].name)}` });
        else coverage.push({ item: label, outcome: 'skipped', reason: 'event variant not listed in components.json' });
      }
    }
    state = { info, props: stateProps, commands, events: Object.entries(configured).map(([variant, spec]) => ({ variant, ...spec, nativeProp: `on${entry.tag}${pascal(spec.name)}`, prop: `on${pascal(spec.name)}` })), controlled, ctor: entry.state.ctor };
    for (const member of stateProps) props.push(member);
    for (const e of state.events) {
      const extra = controlled && controlled.event === e.variant ? [{ name: 'eventCount', ts: 'Int32', rust: 'count' }] : [];
      events.push({ method: null, name: e.name, prop: e.prop, nativeProp: e.nativeProp, source: 'state', variant: e.variant, pattern: e.pattern, before: e.before ?? '', payload: { fields: [...e.fields, ...extra] } });
    }
  }

  for (const method of component.others) {
    coverage.push({ item: `${component.name}::${method.name}`, outcome: 'skipped', reason: 'not a builder (takes self by reference or returns another type)' });
  }
  for (const ctor of component.constructors) {
    coverage.push({ item: `${component.name}::${ctor.name}`, outcome: 'generated', reason: 'constructor; the id comes from the node tag' });
  }
  return { entry, component, props, events, coverage, state };
}

function eventPayloadTs(event) {
  if (event.payload.fields.length === 0) return 'null';
  const fields = event.payload.fields.map(f => `${f.name}: ${f.ts === 'boolean' || f.ts === 'string' ? f.ts : `CodegenTypes.${f.ts}`}`).join('; ');
  return `Readonly<{ ${fields} }>`;
}

function eventProp(event, tag) {
  return `on${tag}${pascal(event.name)}`;
}

function tsType(prop) {
  switch (prop.kind) {
    case 'flag':
    case 'bool':
      return 'boolean';
    case 'string':
    case 'icon':
      return 'string';
    case 'int':
      return 'CodegenTypes.Int32';
    case 'float':
    case 'pixels':
    case 'duration':
      return 'CodegenTypes.Double';
    case 'color':
      return 'ColorValue';
    case 'enum':
      return `CodegenTypes.WithDefault<${['unset', ...prop.info.variants.map(kebab)].map(v => `'${v}'`).join(' | ')}, 'unset'>`;
    default:
      throw new Error(`no TS type for ${prop.kind}`);
  }
}

function visibleProps(model, container) {
  return container ? model.props.filter(p => !['label', 'icon', 'loadingIcon'].includes(p.name)) : model.props;
}

function emitSpec(model, container = false) {
  const { entry, events } = model;
  const props = visibleProps(model, container);
  const tag = container ? `${entry.tag}Container` : entry.tag;
  const usesColor = props.some(p => p.kind === 'color');
  const lines = [HEADER_TS];
  if (model.state?.commands.length && !container) lines.push("import type React from 'react';");
  lines.push(`import {\n  codegenNativeComponent,\n${model.state?.commands.length && !container ? '  codegenNativeCommands,\n' : ''}  type CodegenTypes,\n${model.state?.commands.length && !container ? '  type HostComponent,\n' : ''}${usesColor ? '  type ColorValue,\n' : ''}  type ViewProps,\n} from 'react-native';\n`);
  lines.push('export interface NativeProps extends ViewProps {');
  for (const prop of props) lines.push(`  ${prop.name}?: ${tsType(prop)};`);
  if (model.state?.controlled) {
    const c = model.state.controlled;
    lines.push(`  ${c.prop}?: string;\n  default${pascal(c.prop)}?: string;\n  controlled?: boolean;\n  eventCount?: CodegenTypes.Int32;`);
  }
  for (const event of events) {
    lines.push(`  ${eventProp(event, tag)}?: CodegenTypes.DirectEventHandler<${eventPayloadTs(event)}>;`);
  }
  lines.push('}\n');
  if (model.state?.commands.length) {
    const commands = model.state.commands;
    lines.push(`interface NativeCommands {\n${commands.map(c => `  ${camel(c.name)}: (viewRef: React.ElementRef<HostComponent<NativeProps>>${c.args.map(a => `, ${a.name}: ${a.ts}`).join('')}) => void;`).join('\n')}\n}\n`);
  }
  if (model.state?.commands.length && !container) {
    lines.push(`export const Commands = codegenNativeCommands<NativeCommands>({\n  supportedCommands: [${model.state.commands.map(c => `'${camel(c.name)}'`).join(', ')}],\n});\n`);
    lines.push(`export default codegenNativeComponent<NativeProps>('${tag}', {\n  interfaceOnly: true,\n}) as HostComponent<NativeProps>;\n`);
  } else {
    lines.push(`export default codegenNativeComponent<NativeProps>('${tag}', {\n  interfaceOnly: true,\n});\n`);
  }
  return lines.join('\n');
}

function rustApply(prop, ctx) {
  const rustName = snake(prop.name);
  const call = prop.method;
  switch (prop.kind) {
    case 'flag':
      return `if props.${rustName}() {\n            element = element.${call}();\n        }`;
    case 'bool':
      return `if props.${rustName}() {\n            element = element.${call}(true);\n        }`;
    case 'string':
      return `{\n            let value = props.${rustName}();\n            if !value.is_empty() {\n                element = element.${call}(value.to_string());\n            }\n        }`;
    case 'int':
      return `if props.${rustName}() != 0 {\n            element = element.${call}(props.${rustName}() as ${prop.rust});\n        }`;
    case 'float':
      return `if props.${rustName}() != 0.0 {\n            element = element.${call}(props.${rustName}() as ${prop.rust});\n        }`;
    case 'pixels':
      return `if props.${rustName}() > 0.0 {\n            element = element.${call}(gpui::px(props.${rustName}() as f32));\n        }`;
    case 'duration':
      return `if props.${rustName}() > 0.0 {\n            element = element.${call}(std::time::Duration::from_millis(props.${rustName}() as u64));\n        }`;
    case 'color':
      return `if let Some(color) = props.${rustName}() {\n            element = element.${call}(crate::color::hsla(color));\n        }`;
    case 'icon':
      return `{\n            let value = props.${rustName}();\n            if let Some(icon) = crate::generated::icons::parse(value) {\n                element = element.${call}(icon);\n            }\n        }`;
    case 'enum': {
      const enumName = `${ctx.tag}${pascal(prop.name)}`;
      const arms = prop.info.variants
        .map(v => `            ${enumName}::${enumVariantRust(kebab(v))} => element = element.${call}(${prop.info.publicPath.replace(/^gpui_(base|component)/, 'gpui_$1')}::${v}),`)
        .join('\n');
      return `match props.${rustName}() {\n            ${enumName}::Unset => {}\n${arms}\n        }`;
    }
    default:
      throw new Error(`no Rust glue for ${prop.kind}`);
  }
}

const fl = n => (Number.isInteger(n) ? `${n}.0` : `${n}`);

function constructorExpr(model) {
  const { entry, component } = model;
  if (entry.ctor) return entry.ctor;
  const ctors = component.constructors;
  const withId = ctors.find(c => c.name === 'new' && c.inputs.length === 1 && /ElementId/.test(JSON.stringify(c.inputs[0][1])));
  if (withId) return `${component.name}::new(SharedString::from(self.id.clone()))`;
  if (ctors.find(c => c.name === 'new' && c.inputs.length === 0)) return `${component.name}::new()`;
  throw new Error(`${component.name}: no constructor the generator can call; set ctor in components.json`);
}

function emitRust(model, container = false) {
  if (model.state && !container) return emitRustStateful(model);
  const { entry, component, events } = model;
  const props = visibleProps(model, container);
  const tag = container ? `${entry.tag}Container` : entry.tag;
  const snakeTag = snake(tag);
  const ctxInfo = { tag };
  const out = [HEADER_RS];
  out.push(`use gpui::{AnyElement, IntoElement, SharedString, Window};`);
  if (container || entry.fill) out.push(`use gpui::Styled as _;`);
  if (entry.childText) out.push(`use gpui::ParentElement as _;`);
  out.push(`use ${docs.publicPath(docs.find(component.path).index, docs.find(component.path).id) ?? component.path};`);
  const traitImports = new Set();
  for (const t of component.traits) {
    if (/gpui_(base|component)/.test(t)) traitImports.add(t);
  }
  for (const t of [...traitImports]) {
    const hit = docs.find(t);
    const publicPath = hit ? docs.publicPath(hit.index, hit.id) ?? t : t;
    out.push(`#[allow(unused_imports)]\nuse ${publicPath} as _;`);
  }
  out.push('');
  out.push(`use crate::*;\n`);
  out.push(`pub struct ${tag} {\n    id: String,\n}\n`);
  out.push(`impl ${tag}Spec for ${tag} {`);
  out.push(`    fn create(_props: &${tag}Props, cx: &mut ${tag}Context) -> Self {`);
  out.push(`        Self {\n            id: format!("${snakeTag}-{}", cx.tag()),\n        }\n    }\n`);
  if (container && entry.container?.insets) {
    const sizeProp = props.find(p => p.name === 'size');
    const table = entry.container.insets;
    const arms = sizeProp.info.variants
      .map(v => `            ${tag}Size::${enumVariantRust(kebab(v))} => (${table[kebab(v)].map(fl).join(', ')}),`)
      .join('\n');
    const medium = table.medium.map(fl).join(', ');
    out.push(`    fn update(&mut self, props: &${tag}Props, _changed: ${tag}Changed, cx: &mut ${tag}Context) {\n        let (top, right, bottom, left): (f32, f32, f32, f32) = match props.size() {\n            ${tag}Size::Unset => (${medium}),\n${arms}\n        };\n        cx.set_insets(top, right, bottom, left);\n    }\n`);
  } else {
    out.push(`    fn update(&mut self, _props: &${tag}Props, _changed: ${tag}Changed, _cx: &mut ${tag}Context) {}\n`);
  }
  out.push(`    fn render(&mut self, props: &${tag}Props, _window: &mut Window, cx: &mut ${tag}Context) -> AnyElement {`);
  if (events.length) out.push(`        let sender = cx.event_sender();`);
  out.push(`        let mut element = ${constructorExpr(model)};`);
  for (const prop of props.filter(p => !p.extra)) out.push(`        ${rustApply(prop, ctxInfo)}`);
  for (const event of events.filter(e => e.source !== 'state')) {
    const eventStruct = `On${tag}${pascal(event.name)}`;
    const fields = event.payload.fields.map(f => `${snake(f.name)}: ${f.rust}`).join(', ');
    out.push(`        {\n            let sender = sender.clone();\n            element = element.${event.method}(move |event, _window, _cx| {\n                sender.${snake(tag + pascal(event.name))}(${eventStruct} { ${fields} });\n            });\n        }`);
  }
  if (entry.childText) out.push(`        element = element.child(props.${snake(entry.childText)}().to_string());`);
  if (container || entry.fill) out.push(`        element = element.size_full();`);
  out.push(`        element.into_any_element()\n    }\n}\n`);
  return out.join('\n');
}


function rustValueType(prop) {
  switch (prop.kind) {
    case 'flag':
    case 'bool':
      return 'bool';
    case 'string':
    case 'icon':
      return 'String';
    case 'int':
      return 'i32';
    case 'float':
    case 'pixels':
    case 'duration':
      return 'f64';
    case 'enum':
      return null;
    default:
      return null;
  }
}

function stateSetterApply(prop, tag) {
  const rustName = snake(prop.name);
  const args = [];
  let valueExpr;
  let tracked;
  switch (prop.kind) {
    case 'bool':
      tracked = { ty: 'bool', read: `props.${rustName}()`, clone: 'value' };
      valueExpr = 'value';
      break;
    case 'string':
      tracked = { ty: 'String', read: `props.${rustName}().to_string()`, clone: 'value.clone()' };
      valueExpr = 'value.clone()';
      break;
    case 'int':
      tracked = { ty: 'i32', read: `props.${rustName}()`, clone: 'value' };
      valueExpr = `value as ${prop.rust}`;
      break;
    case 'float':
    case 'duration':
    case 'pixels':
      tracked = { ty: 'f64', read: `props.${rustName}()`, clone: 'value' };
      valueExpr = prop.kind === 'duration' ? 'std::time::Duration::from_millis(value as u64)' : prop.kind === 'pixels' ? 'gpui::px(value as f32)' : `value as ${prop.rust}`;
      break;
    case 'enum': {
      const enumName = `${tag}${pascal(prop.name)}`;
      const arms = prop.info.variants
        .map(v => `${enumName}::${enumVariantRust(kebab(v))} => ${prop.info.publicPath}::${v},`)
        .join('\n                    ');
      return {
        field: `applied_${rustName}: Option<${enumName}>`,
        code: `{\n            let value = props.${rustName}();\n            if value != ${enumName}::Unset && self.applied_${rustName} != Some(value) {\n                let mapped = match value {\n                    ${enumName}::Unset => unreachable!(),\n                    ${arms}\n                };\n                state.update(app, |state, cx| state.${prop.method}(${['mapped', prop.needsWindow ? 'window' : null, prop.needsCx ? 'cx' : null].filter(Boolean).join(', ')}));\n                self.applied_${rustName} = Some(value);\n            }\n        }`,
      };
    }
    default:
      return null;
  }
  const call = `state.${prop.method}(${[valueExpr, prop.needsWindow ? 'window' : null, prop.needsCx ? 'cx' : null].filter(Boolean).join(', ')})`;
  return {
    field: `applied_${rustName}: Option<${tracked.ty}>`,
    code: `{\n            let value = ${tracked.read};\n            if self.applied_${rustName}.as_ref() != Some(&value) {\n                state.update(app, |state, cx| ${call});\n                self.applied_${rustName} = Some(${tracked.clone});\n            }\n        }`,
  };
}

function emitRustStateful(model) {
  const { entry, component, events, state } = model;
  const tag = entry.tag;
  const snakeTag = snake(tag);
  const statePath = state.info.publicPath;
  const stateName = state.info.path.split('::').pop();
  const elementState = state.info.methods;
  const setters = state.props.map(p => ({ prop: p, ...stateSetterApply(p, tag) })).filter(x => x.code);
  const controlled = state.controlled;
  const out = [HEADER_RS];
  out.push(`use std::cell::{Cell, RefCell};\nuse std::rc::Rc;\n`);
  out.push(`use gpui::{div, AnyElement, AppContext as _, Entity, IntoElement, ParentElement as _, SharedString, Subscription, Window};`);
  out.push(`use ${docs.publicPath(docs.find(component.path).index, docs.find(component.path).id) ?? component.path};`);
  out.push(`use ${statePath};`);
  const eventEnumPath = state.info.eventEnums[0];
  const enumHit = eventEnumPath && docs.find(eventEnumPath);
  if (enumHit) out.push(`use ${docs.publicPath(enumHit.index, enumHit.id) ?? eventEnumPath};`);
  for (const t of new Set(component.traits.filter(t => /gpui_(base|component)/.test(t)))) {
    const hit = docs.find(t);
    out.push(`#[allow(unused_imports)]\nuse ${hit ? docs.publicPath(hit.index, hit.id) ?? t : t} as _;`);
  }
  out.push('\nuse crate::*;\n');
  out.push(`pub struct ${tag} {\n    id: String,\n    state: Option<Entity<${stateName}>>,\n    subscriptions: Vec<Subscription>,\n    count: Rc<Cell<i32>>,\n    value: Rc<RefCell<String>>,\n    applied_default: bool,\n${setters.map(x => `    ${x.field},`).join('\n')}\n}\n`);
  out.push(`impl ${tag}Spec for ${tag} {`);
  out.push(`    fn create(_props: &${tag}Props, cx: &mut ${tag}Context) -> Self {\n        Self {\n            id: format!("${snakeTag}-{}", cx.tag()),\n            state: None,\n            subscriptions: Vec::new(),\n            count: Rc::new(Cell::new(0)),\n            value: Rc::new(RefCell::new(String::new())),\n            applied_default: false,\n${setters.map(x => `            applied_${snake(x.prop.name)}: None,`).join('\n')}\n        }\n    }\n`);
  out.push(`    fn update(&mut self, _props: &${tag}Props, _changed: ${tag}Changed, _cx: &mut ${tag}Context) {}\n`);
  // commands
  for (const command of state.commands) {
    const args = command.args.map(a => `${snake(a.name)}: ${a.ts === 'string' ? 'String' : a.ts === 'boolean' ? 'bool' : 'i32'}`).join(', ');
    const callArgs = [...command.args.map(a => (a.ts === 'string' ? `${snake(a.name)}.clone()` : snake(a.name))), ...(command.method.needsWindow ? ['window'] : []), 'cx'];
    out.push(`    fn ${snake(command.name)}(&mut self, ${args ? args + ', ' : ''}cx: &mut ${tag}Context) {
        let Some(state) = self.state.clone() else { return };
        let Some(app) = cx.host_mut().app() else { return };
        let Some(handle) = app.windows().into_iter().next() else { return };
        let _ = handle.update(app, |_, window, app| {
            let _ = &window;
            state.update(app, |state, cx| state.${command.name}(${callArgs.join(', ')}));
        });
    }\n`);
  }
  out.push(`    fn render(&mut self, props: &${tag}Props, window: &mut Window, cx: &mut ${tag}Context) -> AnyElement {`);
  out.push(`        let sender = cx.event_sender();\n        let Some(app) = cx.host_mut().app() else { return div().into_any_element() };`);
  out.push(`        if self.state.is_none() {\n            let state = app.new(|cx| ${state.ctor});`);
  out.push(`            let count = self.count.clone();\n            let value = self.value.clone();\n            let sender = sender.clone();`);
  out.push(`            self.subscriptions.push(app.subscribe(&state, move |state, event: &${eventEnumPath.split('::').pop()}, cx| {\n                let _ = (&count, &value);\n                match event {`);
  for (const e of events.filter(ev => ev.source === 'state')) {
    const eventStruct = `On${tag}${pascal(e.name)}`;
    const fields = e.payload.fields.map(f => `${snake(f.name)}: ${f.rust}`).join(', ');
    const isChange = controlled && controlled.event === e.variant;
    const body = [];
    if (e.before) body.push(e.before);
    if (isChange) body.push(`count.set(count.get() + 1);\n                        *value.borrow_mut() = ${controlled.valueExpr};\n                        let count = count.get();`);
    body.push(e.payload.fields.length ? `sender.${snake(tag + pascal(e.name))}(${eventStruct} { ${fields} });` : `sender.${snake(tag + pascal(e.name))}();`);
    out.push(`                    ${e.pattern} => {\n                        ${body.join('\n                        ')}\n                    }`);
  }
  out.push(`                    #[allow(unreachable_patterns)]\n                    _ => {}\n                }\n            }));\n            self.state = Some(state);\n        }\n        let state = self.state.clone().unwrap();`);
  for (const x of setters) out.push(`        ${x.code}`);
  if (controlled) {
    out.push(`        if !self.applied_default {\n            self.applied_default = true;\n            let initial = props.default_${snake(controlled.prop)}().to_string();\n            if !initial.is_empty() {\n                *self.value.borrow_mut() = initial.clone();\n                state.update(app, |state, cx| state.${controlled.setter}(initial, window, cx));\n            }\n        }`);
    out.push(`        if props.controlled() {\n            let wanted = props.${snake(controlled.prop)}().to_string();\n            if props.event_count() >= self.count.get() && wanted != *self.value.borrow() {\n                *self.value.borrow_mut() = wanted.clone();\n                state.update(app, |state, cx| state.${controlled.setter}(wanted, window, cx));\n            }\n        }`);
  }
  out.push(`        let mut element = ${component.name}::new(&state);`);
  for (const prop of model.props.filter(p => p.source !== 'state' && !p.extra)) out.push(`        ${rustApply(prop, { tag })}`);
  out.push(`        element.into_any_element()\n    }\n}\n`);
  return out.join('\n');
}

function cleanTs(prop) {
  switch (prop.kind) {
    case 'flag':
    case 'bool':
      return 'boolean';
    case 'string':
      return 'string';
    case 'icon':
      return 'IconName';
    case 'int':
    case 'float':
    case 'pixels':
    case 'duration':
      return 'number';
    case 'color':
      return 'ColorValue';
    case 'enum':
      return prop.info.variants.map(v => `'${kebab(v)}'`).join(' | ');
    default:
      throw new Error(`no TS type for ${prop.kind}`);
  }
}

function emitWrapper(model) {
  if (model.state) return emitWrapperStateful(model);
  const { entry, component, props, events } = model;
  const name = component.name;
  const lines = [HEADER_TS];
  lines.push(`import React, { forwardRef, type ComponentRef } from 'react';\nimport type { ColorValue, NativeSyntheticEvent, ViewProps } from 'react-native';\nimport Native from './${entry.tag}NativeComponent';\n${entry.container ? `import NativeContainer from './${entry.tag}ContainerNativeComponent';\n` : ''}import type { IconName } from './icons';\n`);
  for (const event of events) {
    const fields = event.payload.fields.map(f => `${f.name}: ${f.ts === 'boolean' ? 'boolean' : 'number'}`).join('; ');
    lines.push(`export type ${name}${pascal(event.name)}Event = NativeSyntheticEvent<Readonly<{ ${fields} }>>;`);
  }
  lines.push(`\nexport interface ${name}Props extends ViewProps {\n  children?: React.ReactNode;`);
  for (const prop of props) lines.push(`  ${prop.name}?: ${cleanTs(prop)};`);
  for (const event of events) lines.push(`  ${event.prop}?: (event: ${name}${pascal(event.name)}Event) => void;`);
  lines.push('}\n');
  const eventMap = events.map(e => `${e.prop}: ${e.nativeProp}`);
  const layout = entry.layout;
  lines.push(`export const ${name} = forwardRef<ComponentRef<typeof Native>, ${name}Props>(function ${name}(props, ref) {`);
  lines.push(`  const { ${events.map(e => e.prop).join(', ')}${events.length ? ', ' : ''}style, children, ...rest } = props;`);
  if (layout && layout.kind !== 'inline-label') {
    if (layout.heights) {
      lines.push(`  const heights = ${JSON.stringify(layout.heights)} as const;`);
      lines.push(`  const height = heights[(props.size as keyof typeof heights) ?? '${layout.defaultSize ?? 'medium'}'] ?? ${Object.values(layout.heights)[0]};`);
    } else {
      lines.push(`  const height = ${layout.height};`);
    }
    if (layout.text) {
      lines.push(`  const width = Math.max(height, Math.ceil((props.${layout.text.prop}?.length ?? 0) * ${layout.text.charWidth} + ${layout.text.padding ?? 0}));`);
    } else if (layout.square) {
      lines.push(`  const width = height;`);
    } else if (layout.width) {
      lines.push(`  const width = ${layout.width};`);
    } else {
      lines.push(`  const width = undefined;`);
    }
  }
  if (layout?.kind === 'inline-label') {
    lines.push(`  const heights = ${JSON.stringify(layout.heights)} as const;`);
    lines.push(`  const height = heights[(props.size as keyof typeof heights) ?? 'medium'] ?? ${layout.heights.medium};`);
    lines.push(`  const width = Math.max(height, Math.ceil((props.${layout.labelProp}?.length ?? 0) * ${layout.charWidth} + ${layout.padding} + (props.${layout.iconProp} ? ${layout.iconWidth} : 0)));`);
  }
  if (entry.container) {
    const eventsForContainer = events.map(e => `      ${eventProp(e, entry.tag + 'Container')}={${e.prop}}`).join('\n');
    const pressEvent = events.find(e => e.name === 'press');
    const forwarded = events.filter(e => e !== pressEvent).map(e => `      ${eventProp(e, entry.tag + 'Container')}={${e.prop}}`).join('\n');
    const pointer = pressEvent
      ? `        onPointerUp={${pressEvent.prop} && !props.disabled ? (event: any) => ${pressEvent.prop}({ nativeEvent: { x: event.nativeEvent.offsetX ?? 0, y: event.nativeEvent.offsetY ?? 0, rightClick: false, shift: false, control: false, alt: false, meta: false } } as ${name}${pascal(pressEvent.name)}Event) : undefined}\n`
      : '';
    lines.push(`  if (React.Children.count(children) > 0) {\n    return (\n      <NativeContainer\n        ref={ref as never}\n        {...rest}\n        style={[{ flexDirection: 'row', alignItems: 'center', justifyContent: 'center', gap: 6, minHeight: ${layout ? 'height' : 0} }, style]}\n${pointer}${forwarded}\n      >\n        {children}\n      </NativeContainer>\n    );\n  }`);
  }
  lines.push(`  return (\n    <Native\n      ref={ref}\n      {...rest}`);
  for (const prop of props) {
    if (prop.kind === 'enum' && prop.name !== prop.name) continue;
  }
  const renamed = props.filter(p => p.kind === 'enum' || p.kind === 'icon');
  lines.push(`      style={[${layout ? '{ height, width }, ' : ''}style]}`);
  for (const e of events) lines.push(`      ${e.nativeProp}={${e.prop}}`);
  lines.push(`    />\n  );\n});\n`);
  return lines.join('\n');
}


function emitWrapperStateful(model) {
  const { entry, component, props, events, state } = model;
  const name = component.name;
  const c = state.controlled;
  const lines = [HEADER_TS];
  lines.push(`import React, { forwardRef, useImperativeHandle, useRef } from 'react';\nimport type { ColorValue, NativeSyntheticEvent, ViewProps } from 'react-native';\nimport Native, { Commands } from './${entry.tag}NativeComponent';\n`);
  const named = events.map(ev => {
    const fields = ev.payload.fields.map(f => `${f.name}: ${f.ts === 'boolean' ? 'boolean' : f.ts === 'string' ? 'string' : 'number'}`).join('; ');
    const type = `${name}${pascal(ev.name)}Event`;
    lines.push(`export type ${type} = NativeSyntheticEvent<${ev.payload.fields.length ? `Readonly<{ ${fields} }>` : 'Readonly<{}>'}>;`);
    return { ev, type };
  });
  lines.push(`\nexport interface ${name}Props extends ViewProps {`);
  for (const prop of props) lines.push(`  ${prop.name}?: ${cleanTs(prop)};`);
  lines.push(`  ${c.prop}?: string;\n  default${pascal(c.prop)}?: string;\n  onChangeText?: (text: string) => void;`);
  for (const { ev, type } of named) lines.push(`  ${ev.prop}?: (event: ${type}) => void;`);
  lines.push('}\n');
  const commandSig = state.commands.map(cmd => `  ${camel(cmd.name)}(${cmd.args.map(a => `${a.name}: ${a.ts}`).join(', ')}): void;`);
  lines.push(`export interface ${name}Handle {\n${commandSig.join('\n')}\n}\n`);
  const eventNames = events.map(e => e.prop);
  lines.push(`export const ${name} = forwardRef<${name}Handle, ${name}Props>(function ${name}(props, ref) {`);
  lines.push(`  const { ${c.prop}, ${eventNames.join(', ')}, onChangeText, style, ...rest } = props;`);
  lines.push(`  const native = useRef<React.ComponentRef<typeof Native>>(null);\n  const count = useRef(0);`);
  lines.push(`  useImperativeHandle(ref, () => ({\n${state.commands.map(cmd => `    ${camel(cmd.name)}: (${cmd.args.map(a => `${a.name}: ${a.ts}`).join(', ')}) => { if (native.current) Commands.${camel(cmd.name)}(native.current${cmd.args.map(a => `, ${a.name}`).join('')}); },`).join('\n')}\n  }));`);
  lines.push(`  return (\n    <Native\n      ref={native}\n      {...rest}\n      style={[{ minHeight: 32 }, style]}\n      ${c.prop}={${c.prop}}\n      controlled={${c.prop} !== undefined}\n      eventCount={count.current}`);
  for (const { ev } of named) {
    if (ev.variant === c.event) {
      lines.push(`      ${ev.nativeProp}={event => {\n        count.current = event.nativeEvent.eventCount;\n        ${ev.prop}?.(event as never);\n        onChangeText?.(event.nativeEvent.text);\n      }}`);
    } else {
      lines.push(`      ${ev.nativeProp}={${ev.prop}}`);
    }
  }
  lines.push(`    />\n  );\n});\n`);
  return lines.join('\n');
}

function emitIcons() {
  const hit = docs.find('gpui_component::icon::IconName');
  const variants = hit.item.inner.enum.variants.map(id => docs.item(hit.index, id).name);
  const kebabs = variants.map(kebab);
  const ts = `${HEADER_TS}export type IconName =\n${kebabs.map(k => `  | '${k}'`).join('\n')};\n`;
  const rs = `${HEADER_RS}use gpui_component::IconName;\n\npub fn parse(name: &str) -> Option<IconName> {\n    Some(match name {\n${variants.map((v, i) => `        "${kebabs[i]}" => IconName::${v},`).join('\n')}\n        _ => return None,\n    })\n}\n`;
  return { ts, rs, count: variants.length };
}

function emitDoc(model) {
  const { entry, component, props, events, coverage } = model;
  const lines = [`---\nid: gpui-kit-${kebab(component.name)}\ntitle: ${component.name}\n---\n`, '<!-- @generated by tools/gpui-kit-gen. Add notes in docs/manual/' + component.name + '.md -->\n'];
  lines.push(`${component.docs.split('\n\n')[0] ?? ''}\n`);
  lines.push('## Props\n\n| Prop | Type | Native method |\n| --- | --- | --- |');
  for (const prop of props) {
    const type = prop.kind === 'enum' ? prop.info.variants.map(v => `\`'${kebab(v)}'\``).join(' \\| ') : `\`${tsType(prop).replace('CodegenTypes.', '')}\``;
    lines.push(`| \`${prop.name}\` | ${type} | \`${component.name}::${prop.method}\` |`);
  }
  lines.push('\n## Events\n\n| Event | Payload |\n| --- | --- |');
  for (const event of events) lines.push(`| \`${event.prop}\` | ${event.payload.fields.map(f => `\`${f.name}\``).join(', ')} |`);
  lines.push('\n## Skipped\n\n| Method | Reason |\n| --- | --- |');
  for (const c of coverage.filter(c => c.outcome === 'skipped')) lines.push(`| \`${c.item}\` | ${c.reason} |`);
  lines.push('');
  return lines.join('\n');
}

function emitScreen(model) {
  const { entry, component, props, events } = model;
  const name = component.name;
  const lines = [HEADER_TS];
  lines.push(`import React, { useState } from 'react';\nimport { Pressable, ScrollView, Text, TextInput, View } from 'react-native';\nimport { ${name} } from '../${name}';\n`);
  lines.push(`export default function ${name}Screen() {`);
  lines.push(`  const [values, setValues] = useState<Record<string, unknown>>({});\n  const [log, setLog] = useState<string[]>([]);`);
  lines.push(`  const set = (key: string, value: unknown) => setValues(current => ({ ...current, [key]: value }));`);
  lines.push(`  const note = (text: string) => setLog(current => [text, ...current].slice(0, 6));`);
  lines.push(`  return (\n    <ScrollView testID="${kebab(name)}-screen" style={{ flex: 1 }} contentContainerStyle={{ padding: 16, gap: 8 }}>`);
  lines.push(`      <View style={{ height: 64 }}>\n        <${name}\n          testID="${kebab(name)}"\n          style={{ width: 200, height: 40 }}`);
  lines.push(`          {...(values as object)}`);
  for (const event of events) {
    lines.push(`          ${event.prop}={event => note('${event.prop} ' + JSON.stringify(event.nativeEvent))}`);
  }
  lines.push(`        />\n      </View>`);
  for (const prop of props) {
    const id = `${kebab(name)}-prop-${kebab(prop.name)}`;
    if (prop.kind === 'flag' || prop.kind === 'bool') {
      lines.push(`      <Pressable testID="${id}" onPress={() => set('${prop.name}', !values['${prop.name}'])}>\n        <Text>${prop.name}: {String(Boolean(values['${prop.name}']))}</Text>\n      </Pressable>`);
    } else if (prop.kind === 'enum') {
      const options = prop.info.variants.map(kebab);
      lines.push(`      <View style={{ flexDirection: 'row', gap: 6, flexWrap: 'wrap' }}>\n        <Text>${prop.name}:</Text>\n${options.map(o => `        <Pressable testID="${id}-${o}" onPress={() => set('${prop.name}', '${o}')}><Text>${o}</Text></Pressable>`).join('\n')}\n      </View>`);
    } else if (prop.kind === 'string' || prop.kind === 'icon' || prop.kind === 'color') {
      lines.push(`      <TextInput testID="${id}" placeholder="${prop.name}" onChangeText={text => set('${prop.name}', text)} />`);
    } else {
      lines.push(`      <Pressable testID="${id}" onPress={() => set('${prop.name}', ((values['${prop.name}'] as number) ?? 0) + 1)}>\n        <Text>${prop.name}: {String(values['${prop.name}'] ?? 0)}</Text>\n      </Pressable>`);
    }
  }
  lines.push(`      <Text testID="${kebab(name)}-log">{log.join('\\n')}</Text>\n    </ScrollView>\n  );\n}\n`);
  return lines.join('\n');
}

function write(path, content) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
}

function main() {
  const models = components.map(buildModel);
  const srcDir = join(moduleDir, 'src/generated');
  const rustDir = join(moduleDir, 'desktop/src/generated');
  for (const dir of [srcDir, rustDir]) {
    if (existsSync(dir)) rmSync(dir, { recursive: true });
  }
  const modules = [];
  const specs = [];
  const hostComponents = [];
  const coverage = [];
  for (const model of models) {
    const { entry, component } = model;
    write(join(srcDir, `${entry.tag}NativeComponent.ts`), emitSpec(model));
    write(join(srcDir, 'screens', `${component.name}Screen.tsx`), emitScreen(model));
    write(join(srcDir, `${component.name}.tsx`), emitWrapper(model));
    write(join(rustDir, `${snake(entry.tag)}.rs`), emitRust(model));
    write(join(moduleDir, '../../docs/gpui-kit', `${kebab(component.name)}.md`), emitDoc(model));
    modules.push({ tag: entry.tag, group: entry.group });
    specs.push(`../src/generated/${entry.tag}NativeComponent.ts`);
    hostComponents.push({ name: entry.tag });
    if (entry.container) {
      const tag = `${entry.tag}Container`;
      write(join(srcDir, `${tag}NativeComponent.ts`), emitSpec(model, true));
      write(join(rustDir, `${snake(tag)}.rs`), emitRust(model, true));
      modules.push({ tag, group: entry.group });
      specs.push(`../src/generated/${tag}NativeComponent.ts`);
      hostComponents.push({ name: tag, container: true });
    }
    for (const c of model.coverage) coverage.push({ component: component.name, ...c });
  }
  write(
    join(rustDir, 'mod.rs'),
    `${HEADER_RS}pub mod icons;\n${modules.map(m => `#[cfg(feature = "${m.group}")]\npub mod ${snake(m.tag)};`).join('\n')}\n\npub fn register() {\n${modules
      .map(m => `    #[cfg(feature = "${m.group}")]\n    react_native_gpui::host_component::register_component(crate::${snake(m.tag)}_component::<${snake(m.tag)}::${m.tag}>());`)
      .join('\n')}\n}\n`,
  );
  write(join(moduleDir, 'desktop/build.rs'), `${HEADER_RS}fn main() {\n    rn_gpui_module_build::generate(&[\n${specs.map(s => `        "${s}",`).join('\n')}\n    ]);\n}\n`);
  write(
    join(moduleDir, 'react-native.config.js'),
    `${HEADER_TS}module.exports = {\n  dependency: {\n    platforms: {\n      desktop: {\n        crate: 'rn-gpui-gpui-kit',\n        hostComponents: [\n${hostComponents.map(n => `          { name: '${n.name}'${n.container ? ', container: true' : ''} },`).join('\n')}\n        ],\n      },\n    },\n  },\n};\n`,
  );
  const icons = emitIcons();
  write(join(srcDir, 'icons.ts'), icons.ts);
  write(join(rustDir, 'icons.rs'), icons.rs);
  write(
    join(srcDir, 'index.ts'),
    `${HEADER_TS}${models.map(m => `export { ${m.component.name}, type ${m.component.name}Props${m.state ? `, type ${m.component.name}Handle` : ''} } from './${m.component.name}';`).join('\n')}\nexport type { IconName } from './icons';\n`,
  );
  const deferred = JSON.parse(readFileSync(join(here, 'deferred.json'), 'utf8'));
  const counts = {};
  for (const c of coverage) counts[c.outcome] = (counts[c.outcome] ?? 0) + 1;
  write(join(here, 'COVERAGE.json'), JSON.stringify({ counts, items: coverage }, null, 2) + '\n');
  write(
    join(here, 'COVERAGE.md'),
    `# Coverage\n\n${Object.entries(counts).map(([k, v]) => `${k}: ${v}`).join(', ')}\n\n## Components not generated yet\n\n${deferred.map(d => `- ${d.component}: ${d.reason}`).join('\n')}\n\n## Items\n\n| Component | Item | Outcome | Prop | Reason |\n| --- | --- | --- | --- | --- |\n${coverage.map(c => `| ${c.component} | \`${c.item}\` | ${c.outcome} | ${c.prop ?? ''} | ${c.reason} |`).join('\n')}\n`,
  );
  console.log(JSON.stringify(counts));
}

main();
